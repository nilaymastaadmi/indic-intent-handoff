"""Every pre-registered number, generated from results/preds/*.jsonl into results/RESULTS.md."""
import json
import os
from collections import defaultdict

import numpy as np

from iih.data import LOCALES, ROOT
from iih.metrics import accuracy, acceptance_at_retention, at_threshold, auroc, bootstrap, macro_f1, \
    threshold_at_retention

RES = ROOT / os.environ.get("IIH_RESULTS", "results")
INDIC = LOCALES[1:]
SEEDS = (0, 1, 2)


def load(name):
    """{(split, locale): {"known": [recs], "unknown": [recs]}}, known rows sorted by id (parallel)."""
    out = defaultdict(lambda: {"known": [], "unknown": []})
    path = RES / "preds" / f"{name}.jsonl"
    if not path.exists():
        return None
    for r in map(json.loads, path.open(encoding="utf-8")):
        out[(r["split"], r["locale"])]["unknown" if r["unknown"] else "known"].append(r)
    for v in out.values():
        v["known"].sort(key=lambda r: r["id"])
    return out


def runs(arm, regime):
    """The prediction sets of one arm and regime: 3 seeds for A3, 1 otherwise. Missing = []."""
    names = [f"{arm}_{regime}_s{s}" for s in SEEDS] if arm == "A3" else [f"{arm}_{regime}"]
    return [p for p in map(load, names) if p is not None]


def acc_on(p, loc, idx=None):
    k = p[("test", loc)]["known"]
    k = k if idx is None else [k[i] for i in idx]
    return accuracy([r["gold"] for r in k], [r["pred"] for r in k])


def mean_acc(ps, loc, idx=None):
    return float(np.mean([acc_on(p, loc, idx) for p in ps]))


def handoff(p, loc, key):
    t = p[("test", loc)]
    kn, un = [r[key] for r in t["known"]], [r[key] for r in t["unknown"]]
    thr = threshold_at_retention([r[key] for r in p[("dev_en", "en-US")]["known"]])
    return {"auroc": auroc(kn, un), "accept95": acceptance_at_retention(kn, un),
            **dict(zip(("retain_at_en_thr", "caught_at_en_thr"), at_threshold(kn, un, thr)))}


def fmt(ps, loc, n):
    vals = [acc_on(p, loc) for p in ps]
    lo, hi = bootstrap(lambda i: mean_acc(ps, loc, i), n)
    spread = f", seeds {min(vals):.1%} to {max(vals):.1%}" if len(vals) > 1 else ""
    return f"{np.mean(vals):.1%} [{lo:.1%}, {hi:.1%}]{spread}"


def main():
    out = ["# Results (generated by `python -m iih.analyse`; do not edit by hand)", ""]
    arms = {(a, g): runs(a, g) for a in ("A0", "A1", "A2", "A3") for g in ("en", "joint")}
    have = {k: len(v) for k, v in arms.items()}
    out.append("Runs found: " + ", ".join(f"{a}-{g} {n}" for (a, g), n in have.items()))
    unseal = (RES / "UNSEAL.log").read_text(encoding="utf-8").strip().splitlines() if (RES / "UNSEAL.log").exists() else []
    out.append(f"Test split opened {len(unseal)} time(s) (results/UNSEAL.log).")
    any_run = next(v[0] for v in arms.values() if v)
    n_known = len(any_run[("test", "en-US")]["known"])
    n_unknown = len(any_run[("test", "en-US")]["unknown"])
    out.append(f"Known test utterances per locale: {n_known}; unknown: {n_unknown}.")

    v1 = json.loads((RES / "v1.json").read_text()) if (RES / "v1.json").exists() else None
    void = []
    if v1 is None:
        void.append("V1 not run")
    elif abs(v1["mean_acc"] - v1["reference"]) > v1["tolerance"]:
        void.append(f"V1 FAILED: frozen MTEB-protocol accuracy {v1['mean_acc']:.1%} vs {v1['reference']:.1%}: A2 void")
    en_acc = {k: mean_acc(v, "en-US") for k, v in arms.items() if v}
    for arm in ("A2", "A3"):
        if (arm, "en") in en_acc and en_acc[(arm, "en")] < 0.703:
            void.append(f"V2: {arm} EN-only English accuracy {en_acc[(arm, 'en')]:.1%} < 70.3%: {arm} void")
    tr = RES / "train.jsonl"
    failed = [r for r in map(json.loads, tr.open(encoding="utf-8"))] if tr.exists() else []
    failed = [r for r in failed if r["dev_acc_en"] < 0.5]
    if failed:
        void.append(f"V3: {len(failed)} A3 seed(s) below 50% English dev accuracy")
    if n_unknown < 100:
        void.append(f"V4: only {n_unknown} unknown utterances per locale")
    a2_void = v1 is None or abs(v1["mean_acc"] - v1["reference"]) > v1["tolerance"]
    lab = {a: f"{a} (VOID)" if a == "A2" and a2_void else a for a in ("A0", "A1", "A2", "A3")}
    out += ["", f"V1 pipeline check: {v1['mean_acc']:.1%} (reference 70.3% +/- 2.0)" if v1 else "V1: not run",
            "**VOID: " + "; ".join(void) + "**" if void else "Void checks V1 to V4 passed.", ""]

    out += ["## Known-intent accuracy on test (mean over seeds, 95% bootstrap CI)", "",
            "| Arm | Regime | " + " | ".join(LOCALES) + " |", "|---|---|" + "---|" * len(LOCALES)]
    for (a, g), ps in arms.items():
        if ps:
            out.append(f"| {lab[a]} | {g} | " + " | ".join(fmt(ps, l, n_known) for l in LOCALES) + " |")
    out += ["", "Macro-F1 (mean over seeds): " + "; ".join(
        f"{a}-{g} en {np.mean([macro_f1([r['gold'] for r in p[('test', 'en-US')]['known']], [r['pred'] for r in p[('test', 'en-US')]['known']]) for p in ps]):.1%}"
        for (a, g), ps in arms.items() if ps)]

    out += ["", "## Paired difference, A3 LoRA minus A2 frozen (points, 95% bootstrap CI, A3 seed range; AMENDMENTS.md A2)"
            + ("; A2 VOID by V1, printed for the record and not interpreted" if a2_void else ""),
            "", "| Regime | " + " | ".join(LOCALES) + " |", "|---|" + "---|" * len(LOCALES)]
    for g in ("en", "joint"):
        a3, a2 = arms[("A3", g)], arms[("A2", g)]
        if a3 and a2:
            cells = []
            for l in LOCALES:
                lo, hi = bootstrap(lambda i: mean_acc(a3, l, i) - mean_acc(a2, l, i), n_known)
                ds = [100 * (acc_on(p, l) - acc_on(a2[0], l)) for p in a3]
                cells.append(f"{np.mean(ds):+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}], seeds {min(ds):+.1f} to {max(ds):+.1f}")
            out.append(f"| {g} | " + " | ".join(cells) + " |")

    a3en, a3j, a2en = arms[("A3", "en")], arms[("A3", "joint")], arms[("A2", "en")]
    gaps, rec = {}, {}
    if a3en:
        gaps = {l: mean_acc(a3en, "en-US") - mean_acc(a3en, l) for l in INDIC}
        out += ["", "## Zero-shot gap, A3 EN-only (English minus locale, points)", "",
                " | ".join(f"{l} {100 * g:.1f}" for l, g in gaps.items())]
    if a3en and a3j:
        rec = {l: (mean_acc(a3j, l) - mean_acc(a3en, l)) / gaps[l] for l in INDIC if gaps[l] > 0}
        out += ["", "Gap recovered by JOINT: " + " | ".join(f"{l} {r:.0%}" for l, r in rec.items())
                + f" | mean {np.mean(list(rec.values())):.0%}"]

    out += ["", "## Hand-off to a person on unseen intents (unknown = positive)", "",
            "| Arm | Regime | Score | Locale | AUROC | Unknowns let through at 95% known retention | "
            "Known kept at English-dev threshold | Unknowns caught at English-dev threshold |",
            "|---|---|---|---|---|---|---|---|"]
    hand = {}
    for (a, g), ps in arms.items():
        for key in ("msp", "maha"):
            if not ps or ps[0][("test", "en-US")]["known"][0].get(key) is None:
                continue
            for l in LOCALES:
                h = {m: float(np.mean([handoff(p, l, key)[m] for p in ps])) for m in handoff(ps[0], l, key)}
                hand[(a, g, key, l)] = h
                out.append(f"| {lab[a]} | {g} | {key} | {l} | {h['auroc']:.3f} | {h['accept95']:.1%} | "
                           f"{h['retain_at_en_thr']:.1%} | {h['caught_at_en_thr']:.1%} |")

    def verdict(ok):
        return "PASS" if ok else "FAIL"
    out += ["", "## Prediction scorecard", ""]
    if a3en and a2en:
        d = mean_acc(a3en, "en-US") - mean_acc(a2en, "en-US")
        lo, hi = bootstrap(lambda i: mean_acc(a3en, "en-US", i) - mean_acc(a2en, "en-US", i), n_known)
        out.append(f"- P1 LoRA beats frozen by >= 5.0 points in English: {100 * d:+.1f} points "
                   f"[{100 * lo:+.1f}, {100 * hi:+.1f}]: {'VOID (V1 failed, so A2 is void)' if a2_void else verdict(d >= 0.05)}")
    if gaps:
        n10 = sum(g >= 0.10 for g in gaps.values())
        smallest = min(gaps, key=gaps.get)
        out.append(f"- P2 gap >= 10 on >= 4 of 5 locales: {n10} of 5, {verdict(n10 >= 4)}; "
                   f"hi-IN smallest gap: smallest is {smallest}, {verdict(smallest == 'hi-IN')}")
    if rec:
        out.append(f"- P3 JOINT recovers >= 50% of the gap: {np.mean(list(rec.values())):.0%}, "
                   f"{verdict(np.mean(list(rec.values())) >= 0.5)}")
    if ("A3", "en", "msp", "en-US") in hand:
        m = hand[("A3", "en", "msp", "en-US")]["auroc"]
        out.append(f"- P4 MSP AUROC in English < 0.80: {m:.3f}, {verdict(m < 0.80)}")
    if ("A3", "en", "maha", "en-US") in hand:
        m = hand[("A3", "en", "maha", "en-US")]["auroc"] - hand[("A3", "en", "msp", "en-US")]["auroc"]
        out.append(f"- P5 Mahalanobis >= MSP + 0.03 in English: {m:+.3f}, {verdict(m >= 0.03)}")
        low = sum(hand[("A3", "en", "msp", l)]["retain_at_en_thr"] < 0.90 for l in INDIC)
        out.append(f"- P6 English threshold keeps < 90% of knowns on >= 3 of 5 locales (MSP): {low} of 5, "
                   f"{verdict(low >= 3)}")
    if a3en:
        zs = float(np.mean([mean_acc(a3en, l) for l in INDIC]))
        out.append(f"- P7 EN-only 5-locale zero-shot mean in [55, 70]: {zs:.1%}, {verdict(0.55 <= zs <= 0.70)}")
    (RES / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
